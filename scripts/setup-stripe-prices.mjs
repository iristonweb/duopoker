/**
 * Creates DP CLUB subscription products/prices in Stripe (test or live).
 *
 * Usage:
 *   STRIPE_SECRET_KEY=sk_test_... node scripts/setup-stripe-prices.mjs
 *   STRIPE_SECRET_KEY=sk_test_... node scripts/setup-stripe-prices.mjs --write-env
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const require = createRequire(join(root, 'apps/backend/package.json'));
const Stripe = require('stripe');

const TIERS = [
  { key: 'BRONZE', amountRub: 290, label: 'DP CLUB Bronze Club' },
  { key: 'SILVER', amountRub: 490, label: 'DP CLUB Silver Club' },
  { key: 'GOLD', amountRub: 990, label: 'DP CLUB Gold Club' },
  { key: 'PLATINUM', amountRub: 1990, label: 'DP CLUB Platinum Club' },
  { key: 'DIAMOND', amountRub: 2990, label: 'DP CLUB Diamond Club' },
  { key: 'BLACK', amountRub: 4990, label: 'DP CLUB Black Club' }
];

const loadDotEnv = (filePath) => {
  if (!existsSync(filePath)) return;
  const text = readFileSync(filePath, 'utf8');
  for (const line of text.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const k = trimmed.slice(0, eq).trim();
    const v = trimmed.slice(eq + 1).trim();
    if (!process.env[k]) process.env[k] = v;
  }
};

loadDotEnv(join(root, 'apps/backend/.env'));
loadDotEnv(join(root, '.env'));

const writeEnv = process.argv.includes('--write-env');
const secret = process.env.STRIPE_SECRET_KEY?.trim();

if (!secret) {
  console.error(
    'STRIPE_SECRET_KEY is required.\n' +
      'Get it from https://dashboard.stripe.com/test/apikeys then run:\n' +
      '  STRIPE_SECRET_KEY=sk_test_... pnpm stripe:setup:env'
  );
  process.exit(1);
}

const stripe = new Stripe(secret);

const findExistingPrice = async (tier) => {
  const prices = await stripe.prices.list({ limit: 100, active: true, expand: ['data.product'] });
  return prices.data.find(
    (p) =>
      p.metadata?.dpClubTier === tier &&
      p.currency === 'rub' &&
      p.recurring?.interval === 'month' &&
      p.unit_amount === TIERS.find((t) => t.key === tier).amountRub * 100
  );
};

const ensurePrice = async (tierDef) => {
  const existing = await findExistingPrice(tierDef.key);
  if (existing) {
    console.log(`[exists] ${tierDef.key} -> ${existing.id}`);
    return existing.id;
  }

  const product = await stripe.products.create({
    name: tierDef.label,
    description: `Monthly ${tierDef.label} subscription — play-money cosmetics & perks.`,
    metadata: { dpClubTier: tierDef.key, productFamily: 'dp_club_subscription' }
  });

  const price = await stripe.prices.create({
    product: product.id,
    currency: 'rub',
    unit_amount: tierDef.amountRub * 100,
    recurring: { interval: 'month' },
    metadata: { dpClubTier: tierDef.key }
  });

  console.log(`[created] ${tierDef.key} -> ${price.id} (${tierDef.amountRub} RUB/mo)`);
  return price.id;
};

const main = async () => {
  const ids = {};
  for (const tier of TIERS) {
    ids[tier.key] = await ensurePrice(tier);
  }

  const envLines = [
    '',
    '# DP CLUB subscriptions (generated by scripts/setup-stripe-prices.mjs)',
    `STRIPE_PRICE_BRONZE=${ids.BRONZE}`,
    `STRIPE_PRICE_SILVER=${ids.SILVER}`,
    `STRIPE_PRICE_GOLD=${ids.GOLD}`,
    `STRIPE_PRICE_PLATINUM=${ids.PLATINUM}`,
    `STRIPE_PRICE_DIAMOND=${ids.DIAMOND}`,
    `STRIPE_PRICE_BLACK=${ids.BLACK}`
  ];

  console.log('\n--- Add to .env ---');
  console.log(envLines.join('\n'));

  if (writeEnv) {
    const envPath = join(root, 'apps/backend/.env');
    let body = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
    body = body
      .replace(/^#?\s*STRIPE_PRICE_(BRONZE|SILVER|GOLD|PLATINUM|DIAMOND|BLACK|ROYAL)=.*\n?/gm, '')
      .replace(/\n# DP CLUB subscriptions \(generated by scripts\/setup-stripe-prices\.mjs\)[\s\S]*?(?=\n# |\n*$)/, '\n')
      .trimEnd();
    writeFileSync(envPath, `${body}\n${envLines.join('\n')}\n`, 'utf8');
    console.log(`\nUpdated ${envPath}`);
  }
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
